export const DARK_THEMES = THEME_PRESETS.filter((t) => t.category === 'dark');
export const LIGHT_THEMES = THEME_PRESETS.filter((t) => t.category === 'light');

export const getThemeById = (id: string): ThemePreset => {
  const found = THEME_PRESETS.find((t) => t.id === id);
  if (found) return found;
  return THEME_PRESETS[0];
};

export const applyTheme = (themeId: string) => {
  const theme = getThemeById(themeId);
  document.documentElement.setAttribute('data-theme', theme.id);
  localStorage.setItem('theme', theme.id);
  return theme;
};
